"""
benchmark_dataset.py — Comprehensive evaluation benchmark dataset for Verity (M2.4).

Contains 24 representative test cases categorized across:
- correct (grounded, factual)
- contradictory / incorrect (asserts disproven falsehoods)
- partially_correct (mix of true facts and unverified/unsupported assertions)
- irrelevant / off_topic (tangential or completely unrelated responses)
- incomplete / insufficient_evidence (prompt criteria unaddressed or reference lacking)
- unsupported_claims (smoothly worded fabrications)
- consistency_pairs (semantically equivalent responses for variance validation)
"""

from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field


class BenchmarkTestCase(BaseModel):
    """Structured contract for an individual evaluation benchmark case."""
    id: str = Field(..., description="Unique case identifier, e.g. 'TC-COR-01'")
    name: str = Field(..., description="Short descriptive title of the test case")
    category: str = Field(
        ...,
        description="'correct' | 'contradictory' | 'partially_correct' | 'irrelevant' | 'incomplete' | 'unsupported_claims' | 'consistency_pair'"
    )
    dataset_origin: str = Field(..., description="'truthfulqa' | 'squad' | 'curated'")
    question: str
    ai_response: str
    reference_answer: Optional[str] = None
    source_document: Optional[str] = None

    # Expected behavior contracts
    expected_relevance_class: str
    expected_relevance_min_score: float
    expected_relevance_max_score: float

    expected_accuracy_class: str
    expected_accuracy_min_score: float
    expected_accuracy_max_score: float

    expected_hallucination_detected: bool
    expected_hallucination_severity: str

    pair_id: Optional[str] = None


